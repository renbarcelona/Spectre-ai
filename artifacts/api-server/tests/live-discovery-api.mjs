const base = "http://localhost:80/api";
async function call(path, data, credential = `sid=${sid}`, method = data ? "POST" : "GET") {
  const headers = { "Content-Type": "application/json" };
  if (credential?.startsWith("sid=")) headers.Cookie = credential;
  else if (credential) headers.Authorization = `Bearer ${credential}`;
  const r = await fetch(base + path, { method, headers, ...(data ? { body: JSON.stringify(data) } : {}) });
  return { status: r.status, data: await r.json() };
}
